-- quiz-maker 표·색인·트리거·권한·RLS (설계서 2.3절). schema_version 1.
-- 다시 돌려도 같은 결과가 나오게 쓴다(create if not exists, create or replace, drop … if exists 뒤 create).
-- 운영에 적용된 뒤에는 이 파일을 고치지도, 지우지도, 이름을 바꾸지도 않는다. 바꿀 것은 새 파일로(supabase/README.md).

-- 기본 권한: 이 역할(마이그레이션을 돌리는 역할)이 앞으로 만드는 함수·표·시퀀스가 저절로 anon 에 열리지 않게 한다.
-- Postgres 기본값은 새 함수를 PUBLIC(anon 포함)이 실행할 수 있게 하고, 표 자동 노출이 켜진 프로젝트는 public 의
-- 새 표·함수·시퀀스를 anon 에 준다. 다음 마이그레이션이 권한 명시를 빠뜨려도 anon 은 막힌다.
-- PUBLIC 의 기본 실행 권한은 스키마 단위로 거둘 수 없어 첫 줄은 전역이다(이 역할이 어느 스키마에 만드는 함수에나 걸림).
-- authenticated 에 대한 자동 부여에도 기대지 않는다: 새 표·함수는 늘 권한을 명시한다(supabase/README.md 규칙 8).
alter default privileges revoke execute on functions from public;
alter default privileges in schema public revoke all on functions from anon;
alter default privileges in schema public revoke all on tables    from anon;
alter default privileges in schema public revoke all on sequences from anon;

-- 설정 한 줄
create table if not exists public.qm_settings (
  id                 boolean primary key default true,
  live               boolean not null default false,   -- true: 전환 끝. 옮기기·비우기가 막히고, 운영 주소의 앱은 이때만 동작
  schema_version     integer not null default 0,
  imported_at        timestamptz,                       -- 마지막 넣기 끝(qm_import_finish) 시각
  import_max         jsonb,                             -- 그때 표의 최대 id {sets, questions, notes}
  last_user_write_at timestamptz,                       -- 사용자 요청(authenticated)이 세 표에 마지막으로 쓴 시각
  constraint qm_settings_one_row check (id)
);
insert into public.qm_settings (id) values (true) on conflict (id) do nothing;

create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete restrict,  -- Users 화면에서 지우려 하면 오류
  username   varchar(50) not null,                 -- 필기·하드모드 열쇠, 도구 ledger 와 같은 이름
  nickname   varchar(50),
  role       text not null default 'USER',
  created_at timestamptz not null default now(),
  constraint profiles_role_check check (role in ('USER', 'MANAGER', 'ADMIN'))
);
create unique index if not exists profiles_username_lower_key on public.profiles (lower(username));
create unique index if not exists profiles_one_admin on public.profiles ((true)) where role = 'ADMIN';  -- 관리자는 하나뿐

create table if not exists public.question_sets (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references public.profiles (id) on delete restrict,
  title      varchar(100) not null,
  subject    varchar(50),
  created_at timestamptz not null default now()
);
create index if not exists question_sets_user_created_idx
  on public.question_sets (user_id, created_at desc, id desc);

create table if not exists public.questions (
  id                 bigint generated by default as identity primary key,
  set_id             bigint not null references public.question_sets (id) on delete cascade,
  type               varchar(20),
  text               text,
  options            text,            -- 객관식 보기: JSON 글자(옛 MySQL JSON 꼴 그대로)
  answer_index       integer,
  answer             varchar(500),
  answers            jsonb,           -- fill 정답 배열, 빈 배열은 NULL
  explanation        text,
  question_image_url varchar(500),
  answer_image_url   varchar(500),
  order_index        integer not null default 0,
  constraint questions_text_bytes        check (text is null or octet_length(text) <= 65535),          -- 옛 MySQL TEXT 한도
  constraint questions_explanation_bytes check (explanation is null or octet_length(explanation) <= 65535),
  constraint questions_answers_array     check (answers is null or jsonb_typeof(answers) = 'array')
);
create index if not exists questions_set_order_idx on public.questions (set_id, order_index, id);

create table if not exists public.question_notes (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references public.profiles (id) on delete restrict,
  set_id      bigint references public.question_sets (id) on delete set null,   -- 문제집을 지우면 떼어짐
  question_id bigint references public.questions (id) on delete set null,       -- 문항을 지우면 떼어짐
  set_title   varchar(100),          -- 쓸 때의 문제집 제목(트리거가 복사, 나중에 제목이 바뀌어도 그대로)
  blank_no    integer,
  context     text,
  content     text not null,
  resolved_at timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint question_notes_content_len check (char_length(content) between 1 and 2000),
  constraint question_notes_context_len check (context is null or char_length(context) <= 1000),
  constraint question_notes_blank_no    check (blank_no is null or blank_no >= 1)
);
create index if not exists question_notes_user_created_idx
  on public.question_notes (user_id, created_at desc, id desc);
create index if not exists question_notes_set_question_idx on public.question_notes (set_id, question_id);
create index if not exists question_notes_question_idx     on public.question_notes (question_id);

-- 밖(Data API)으로 드러나지 않는 도움 함수 자리. 노출 스키마 목록에 넣지 않는다.
create schema if not exists qm_private;
revoke all on schema qm_private from public;
grant usage on schema qm_private to authenticated;

-- 사용자 쓰기 시각 남기기(소유자 권한으로 설정 줄만 고침)
create or replace function qm_private.touch_user_write() returns void
language sql security definer set search_path = '' as $$
  update public.qm_settings set last_user_write_at = now()
$$;
revoke execute on function qm_private.touch_user_write() from public, anon;
grant execute on function qm_private.touch_user_write() to authenticated;

-- 문장 단위 트리거: 사용자 요청일 때만 남긴다(옮기기 함수는 소유자 권한이라 남지 않음).
-- 바뀐 행이 0인 문장(직접 REST 의 빈 DELETE 등)도 남긴다. 비우기를 막는 쪽으로만 틀리므로 받아들인다.
create or replace function public.qm_after_user_write() returns trigger
language plpgsql set search_path = '' as $$
begin
  if current_user = 'authenticated' then
    perform qm_private.touch_user_write();
  end if;
  return null;
end $$;
drop trigger if exists qm_user_write on public.question_sets;
create trigger qm_user_write after insert or update or delete on public.question_sets
  for each statement execute function public.qm_after_user_write();
drop trigger if exists qm_user_write on public.questions;
create trigger qm_user_write after insert or update or delete on public.questions
  for each statement execute function public.qm_after_user_write();
drop trigger if exists qm_user_write on public.question_notes;
create trigger qm_user_write after insert or update or delete on public.question_notes
  for each statement execute function public.qm_after_user_write();

-- 앞뒤 공백 빼기(옛 Java String.strip() 대응).
-- 공백의 범위를 Java Character.isWhitespace 와 같게 적는다(\s 는 DB 로캘에 따라 전각 공백 U+3000 등을 못 볼 수 있음).
-- 줄 바꿈 없는 공백(U+00A0, U+2007, U+202F)은 Java 처럼 남긴다.
create or replace function public.qm_strip(v text) returns text
language sql immutable set search_path = '' as $$
  select regexp_replace(v,
    '^[\u0009-\u000d\u001c-\u0020\u1680\u2000-\u2006\u2008-\u200a\u2028\u2029\u205f\u3000]+|[\u0009-\u000d\u001c-\u0020\u1680\u2000-\u2006\u2008-\u200a\u2028\u2029\u205f\u3000]+$',
    '', 'g')
$$;

-- 메모 넣기: 사용자 요청(authenticated)일 때만 고친다.
-- 옮기기 함수(소유자 권한)로 넣을 때는 옛 값(set_title·시각)을 그대로 둔다.
create or replace function public.qm_notes_before_insert() returns trigger
language plpgsql set search_path = '' as $$
declare
  v_set_id bigint;
  v_title  text;
begin
  if current_user <> 'authenticated' then
    return new;
  end if;
  new.user_id := auth.uid();
  new.content := public.qm_strip(new.content);
  new.context := nullif(public.qm_strip(new.context), '');
  if new.question_id is not null then
    select q.set_id into v_set_id from public.questions q where q.id = new.question_id;   -- RLS: 내 문항만 보임
    if v_set_id is null then
      raise exception using errcode = 'QM404', message = '존재하지 않는 문항입니다.';
    end if;
    if new.set_id is not null and new.set_id <> v_set_id then
      raise exception using errcode = 'QM400', message = '고른 문항이 그 문제집의 문항이 아닙니다.';
    end if;
    new.set_id := v_set_id;
  end if;
  if new.set_id is not null then
    select s.title into v_title from public.question_sets s where s.id = new.set_id;
    if not found then
      raise exception using errcode = 'QM404', message = '존재하지 않는 문제집입니다.';
    end if;
    new.set_title := v_title;
  else
    new.set_title := null;
  end if;
  new.resolved_at := null;
  new.created_at  := date_trunc('milliseconds', now());
  new.updated_at  := new.created_at;
  return new;
end $$;
drop trigger if exists qm_notes_before_insert on public.question_notes;
create trigger qm_notes_before_insert before insert on public.question_notes
  for each row execute function public.qm_notes_before_insert();

-- 메모 고치기: 사용자 요청일 때만 updated_at 을 갱신한다.
-- 외래키 떼기(set null)는 표 주인 권한으로 돌아서 updated_at 이 바뀌지 않는다(옛 detach 와 같음).
create or replace function public.qm_notes_before_update() returns trigger
language plpgsql set search_path = '' as $$
begin
  if current_user = 'authenticated' then
    new.updated_at := date_trunc('milliseconds', now());
  end if;
  return new;
end $$;
drop trigger if exists qm_notes_before_update on public.question_notes;
create trigger qm_notes_before_update before update on public.question_notes
  for each row execute function public.qm_notes_before_update();

-- 권한: 표 단위로 모두 거둔 뒤(칸 권한도 함께 거둬짐) 필요한 칸만 준다.
-- id·user_id 칸은 사용자 쪽에서 쓸 수 없다(함수를 거치지 않는 직접 쓰기로 번호를 정하거나 바꾸지 못하게).
revoke all on public.qm_settings, public.profiles, public.question_sets,
              public.questions, public.question_notes from anon, authenticated;
grant select                         on public.qm_settings    to authenticated;
grant select                         on public.profiles       to authenticated;
grant select, delete                 on public.question_sets  to authenticated;
grant insert (title, subject),
      update (title, subject)        on public.question_sets  to authenticated;
grant select, delete                 on public.questions      to authenticated;
-- 문항의 set_id 는 넣을 때만 정한다. 다른 문제집으로 옮기는 길은 두지 않는다(옛 API 에 없음, 메모의 짝이 깨짐).
grant insert (set_id, type, text, options, answer_index, answer, answers, explanation,
              question_image_url, answer_image_url, order_index),
      update (type, text, options, answer_index, answer, answers, explanation,
              question_image_url, answer_image_url, order_index)
                                     on public.questions      to authenticated;
grant select, delete                 on public.question_notes to authenticated;
grant insert (set_id, question_id, blank_no, context, content)
                                     on public.question_notes to authenticated;
grant update (content, resolved_at)  on public.question_notes to authenticated;
-- identity 칸의 번호 매기기에는 시퀀스 권한이 필요 없다(1단계 시험으로 확인). 자동 노출 기본값이 준 것도 거둔다.
revoke all on sequence public.question_sets_id_seq, public.questions_id_seq,
                       public.question_notes_id_seq from anon, authenticated;

alter table public.qm_settings    enable row level security;
alter table public.profiles       enable row level security;
alter table public.question_sets  enable row level security;
alter table public.questions      enable row level security;
alter table public.question_notes enable row level security;

-- 설정 줄은 계정 준비가 끝난(프로필이 있는) 사용자만 읽는다. 프로필 없는 로그인(가입 틈·익명)에는 안 보인다.
-- 판 번호는 anon 도 부를 수 있는 qm_schema_version() 이 알려 준다.
drop policy if exists qm_settings_read on public.qm_settings;
create policy qm_settings_read on public.qm_settings for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = (select auth.uid())));

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles for select to authenticated
  using (id = (select auth.uid()));

drop policy if exists sets_select_own on public.question_sets;
create policy sets_select_own on public.question_sets for select to authenticated
  using (user_id = (select auth.uid()));
drop policy if exists sets_insert_own on public.question_sets;
create policy sets_insert_own on public.question_sets for insert to authenticated
  with check (user_id = (select auth.uid()));
drop policy if exists sets_update_own on public.question_sets;
create policy sets_update_own on public.question_sets for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists sets_delete_own on public.question_sets;
create policy sets_delete_own on public.question_sets for delete to authenticated
  using (user_id = (select auth.uid()));

-- 문항: 부모 문제집의 주인만
drop policy if exists questions_select_own on public.questions;
create policy questions_select_own on public.questions for select to authenticated
  using (exists (select 1 from public.question_sets s
                 where s.id = set_id and s.user_id = (select auth.uid())));
drop policy if exists questions_insert_own on public.questions;
create policy questions_insert_own on public.questions for insert to authenticated
  with check (exists (select 1 from public.question_sets s
                      where s.id = set_id and s.user_id = (select auth.uid())));
drop policy if exists questions_update_own on public.questions;
create policy questions_update_own on public.questions for update to authenticated
  using      (exists (select 1 from public.question_sets s where s.id = set_id and s.user_id = (select auth.uid())))
  with check (exists (select 1 from public.question_sets s where s.id = set_id and s.user_id = (select auth.uid())));
drop policy if exists questions_delete_own on public.questions;
create policy questions_delete_own on public.questions for delete to authenticated
  using (exists (select 1 from public.question_sets s
                 where s.id = set_id and s.user_id = (select auth.uid())));

-- 메모: 내 것만. 붙이는 문제집·문항도 내 것이어야 한다(짝 확인은 트리거가 함)
drop policy if exists notes_select_own on public.question_notes;
create policy notes_select_own on public.question_notes for select to authenticated
  using (user_id = (select auth.uid()));
drop policy if exists notes_insert_own on public.question_notes;
create policy notes_insert_own on public.question_notes for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and (set_id is null or exists (select 1 from public.question_sets s
                                   where s.id = set_id and s.user_id = (select auth.uid())))
    and (question_id is null or exists (select 1 from public.questions q
                                        join public.question_sets s on s.id = q.set_id
                                        where q.id = question_id and s.user_id = (select auth.uid())))
  );
drop policy if exists notes_update_own on public.question_notes;
create policy notes_update_own on public.question_notes for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists notes_delete_own on public.question_notes;
create policy notes_delete_own on public.question_notes for delete to authenticated
  using (user_id = (select auth.uid()));

update public.qm_settings set schema_version = greatest(schema_version, 1);
